use srcrelief_facts::Import;
use srcrelief_format::SubKind;
use tree_sitter::{Node, Parser};

#[derive(Clone, Debug, Default, PartialEq)]
pub struct GoFile {
    pub package: String,
    pub imports: Vec<Import>,
    pub types: Vec<GoType>,
    pub funcs: Vec<GoFunc>,
    pub lines: u32,
    pub generated_mock: bool,
}

#[derive(Clone, Debug, PartialEq)]
pub struct GoType {
    pub name: String,
    pub kind: SubKind,
    pub fields: Vec<(String, String)>,
    pub methods: Vec<String>,
    pub arity: Vec<usize>,
    pub embeds: Vec<String>,
    pub start_line: u32,
    pub end_line: u32,
}

#[derive(Clone, Debug, Default, PartialEq)]
pub struct GoFunc {
    pub name: String,
    pub receiver: Option<String>,
    pub params: Vec<(String, String)>,
    pub results: Vec<String>,
    pub locals: Vec<(String, String)>,
    pub calls: Vec<GoCall>,
    pub start_line: u32,
    pub end_line: u32,
}

#[derive(Clone, Debug, Default, PartialEq)]
pub struct GoCall {
    pub receiver: Option<String>,
    pub method: String,
    pub string_args: Vec<Option<String>>,
    pub ident_args: Vec<Option<String>>,
    pub assigned_to: Option<String>,
    pub composite: Option<String>,
    pub line: u32,
}

pub const CHAIN: &str = "<chain>";

pub fn parse_go(src: &[u8]) -> GoFile {
    let mut parser = Parser::new();
    parser.set_language(&tree_sitter_go::LANGUAGE.into()).expect("go grammar");
    let Some(tree) = parser.parse(src, None) else { return GoFile::default() };
    let head = &src[..src.len().min(512)];
    let mut out = GoFile {
        lines: src.iter().filter(|&&b| b == b'\n').count() as u32 + 1,
        generated_mock: String::from_utf8_lossy(head).contains("Code generated by mockery"),
        ..Default::default()
    };
    let c = Ctx { src };
    let root = tree.root_node();
    let mut cur = root.walk();
    for n in root.named_children(&mut cur) {
        match n.kind() {
            "package_clause" => {
                if let Some(id) = first_named_of(n, &["package_identifier"]) {
                    out.package = c.text(id).to_string();
                }
            }
            "import_declaration" => c.imports(n, &mut out.imports),
            "type_declaration" => c.types(n, &mut out.types),
            "function_declaration" | "method_declaration" => out.funcs.push(c.func(n)),
            _ => {}
        }
    }
    out
}

fn first_named_of<'t>(node: Node<'t>, kinds: &[&str]) -> Option<Node<'t>> {
    let mut c = node.walk();
    node.named_children(&mut c).find(|n| kinds.contains(&n.kind()))
}

fn line(n: Node) -> u32 {
    n.start_position().row as u32 + 1
}

fn end_line(n: Node) -> u32 {
    n.end_position().row as u32 + 1
}

struct Ctx<'s> {
    src: &'s [u8],
}

impl<'s> Ctx<'s> {
    fn text(&self, n: Node) -> &'s str {
        n.utf8_text(self.src).unwrap_or("")
    }

    fn string(&self, n: Node) -> String {
        self.text(n).trim_matches('"').trim_matches('`').to_string()
    }

    fn imports(&self, n: Node, out: &mut Vec<Import>) {
        let mut stack = vec![n];
        while let Some(x) = stack.pop() {
            if x.kind() == "import_spec" {
                let path = x.child_by_field_name("path").map(|p| self.string(p)).unwrap_or_default();
                let alias = x.child_by_field_name("name").map(|a| self.text(a).to_string());
                out.push(Import { path, alias, wildcard: false, is_static: false });
                continue;
            }
            let mut c = x.walk();
            let kids: Vec<Node> = x.named_children(&mut c).collect();
            stack.extend(kids.into_iter().rev());
        }
    }

    fn type_name(&self, n: Node) -> String {
        match n.kind() {
            "pointer_type" | "slice_type" | "array_type" | "channel_type" | "parenthesized_type" => {
                let mut c = n.walk();
                n.named_children(&mut c).last().map(|t| self.type_name(t)).unwrap_or_default()
            }
            "generic_type" => n.child_by_field_name("type").map(|t| self.type_name(t)).unwrap_or_default(),
            "map_type" => n.child_by_field_name("value").map(|t| self.type_name(t)).unwrap_or_default(),
            _ => self.text(n).to_string(),
        }
    }

    fn types(&self, n: Node, out: &mut Vec<GoType>) {
        let mut c = n.walk();
        for spec in n.named_children(&mut c) {
            if !matches!(spec.kind(), "type_spec" | "type_alias") {
                continue;
            }
            let Some(name) = spec.child_by_field_name("name") else { continue };
            let ty = spec.child_by_field_name("type");
            let mut t = GoType {
                name: self.text(name).to_string(),
                kind: SubKind::NamedType,
                fields: Vec::new(),
                methods: Vec::new(),
                arity: Vec::new(),
                embeds: Vec::new(),
                start_line: line(spec),
                end_line: end_line(spec),
            };
            match ty.map(|t| t.kind()) {
                Some("struct_type") => {
                    t.kind = SubKind::Struct;
                    if let Some(list) = first_named_of(ty.unwrap(), &["field_declaration_list"]) {
                        let mut fc = list.walk();
                        for fd in list.named_children(&mut fc) {
                            if fd.kind() != "field_declaration" {
                                continue;
                            }
                            let Some(fty) = fd.child_by_field_name("type") else { continue };
                            let fty_name = self.type_name(fty);
                            let mut nc = fd.walk();
                            let names: Vec<String> = fd.children_by_field_name("name", &mut nc).map(|x| self.text(x).to_string()).collect();
                            if names.is_empty() {
                                t.embeds.push(fty_name);
                            } else {
                                for nm in names {
                                    t.fields.push((nm, fty_name.clone()));
                                }
                            }
                        }
                    }
                }
                Some("interface_type") => {
                    t.kind = SubKind::Interface;
                    let it = ty.unwrap();
                    let mut ic = it.walk();
                    for el in it.named_children(&mut ic) {
                        match el.kind() {
                            "method_elem" | "method_spec" => {
                                if let Some(nm) = el.child_by_field_name("name") {
                                    let mut params = Vec::new();
                                    self.params(el.child_by_field_name("parameters"), &mut params);
                                    t.methods.push(self.text(nm).to_string());
                                    t.arity.push(params.len());
                                }
                            }
                            "type_elem" | "constraint_elem" => t.embeds.push(self.text(el).to_string()),
                            _ => {}
                        }
                    }
                }
                _ => {}
            }
            out.push(t);
        }
    }

    fn params(&self, list: Option<Node>, out: &mut Vec<(String, String)>) {
        let Some(list) = list else { return };
        let mut c = list.walk();
        for p in list.named_children(&mut c) {
            if !matches!(p.kind(), "parameter_declaration" | "variadic_parameter_declaration") {
                continue;
            }
            let ty = p.child_by_field_name("type").map(|t| self.type_name(t)).unwrap_or_default();
            let mut nc = p.walk();
            let names: Vec<Node> = p.children_by_field_name("name", &mut nc).collect();
            if names.is_empty() {
                out.push((String::new(), ty.clone()));
            }
            for nm in names {
                out.push((self.text(nm).to_string(), ty.clone()));
            }
        }
    }

    fn func(&self, n: Node) -> GoFunc {
        let mut f = GoFunc {
            name: n.child_by_field_name("name").map(|x| self.text(x).to_string()).unwrap_or_default(),
            start_line: line(n),
            end_line: end_line(n),
            ..Default::default()
        };
        if let Some(recv) = n.child_by_field_name("receiver") {
            let mut r = Vec::new();
            self.params(Some(recv), &mut r);
            if let Some((name, ty)) = r.into_iter().next() {
                f.receiver = Some(ty.clone());
                if !name.is_empty() {
                    f.locals.push((name, ty));
                }
            }
        }
        self.params(n.child_by_field_name("parameters"), &mut f.params);
        if let Some(res) = n.child_by_field_name("result") {
            if res.kind() == "parameter_list" {
                let mut rs = Vec::new();
                self.params(Some(res), &mut rs);
                f.results = rs.into_iter().map(|(_, t)| t).collect();
            } else {
                f.results.push(self.type_name(res));
            }
        }
        if let Some(body) = n.child_by_field_name("body") {
            self.body(body, &mut f);
        }
        f.calls.sort_by_key(|c| c.line);
        f
    }

    fn body(&self, body: Node, f: &mut GoFunc) {
        let mut stack = vec![body];
        while let Some(n) = stack.pop() {
            match n.kind() {
                "call_expression" => f.calls.push(self.call(n)),
                "composite_literal" => {
                    if let Some(t) = n.child_by_field_name("type") {
                        f.calls.push(GoCall { composite: Some(self.type_name(t)), line: line(n), ..Default::default() });
                    }
                }
                "var_spec" => {
                    let ty = n.child_by_field_name("type").map(|t| self.type_name(t));
                    let mut nc = n.walk();
                    let names: Vec<String> = n.children_by_field_name("name", &mut nc).map(|x| self.text(x).to_string()).collect();
                    let values = n.child_by_field_name("value");
                    for (i, nm) in names.into_iter().enumerate() {
                        let t = ty.clone().or_else(|| values.and_then(|v| nth_named(v, i)).and_then(|v| self.expr_type(v)));
                        if let Some(t) = t {
                            f.locals.push((nm, t));
                        }
                    }
                }
                "short_var_declaration" | "assignment_statement" => {
                    if let (Some(left), Some(right)) = (n.child_by_field_name("left"), n.child_by_field_name("right")) {
                        let mut lc = left.walk();
                        let lefts: Vec<String> = left.named_children(&mut lc).map(|x| self.text(x).to_string()).collect();
                        let mut rc = right.walk();
                        let rights: Vec<Node> = right.named_children(&mut rc).collect();
                        if rights.len() == lefts.len() {
                            for (l, r) in lefts.iter().zip(&rights) {
                                if let Some(t) = self.expr_type(*r) {
                                    f.locals.push((l.clone(), t));
                                }
                            }
                        } else if rights.len() == 1 {
                            if let (Some(l), Some(t)) = (lefts.first(), self.expr_type(rights[0])) {
                                f.locals.push((l.clone(), t));
                            }
                        }
                    }
                }
                _ => {}
            }
            let mut c = n.walk();
            let kids: Vec<Node> = n.named_children(&mut c).collect();
            stack.extend(kids.into_iter().rev());
        }
    }

    fn expr_type(&self, n: Node) -> Option<String> {
        match n.kind() {
            "composite_literal" => n.child_by_field_name("type").map(|t| self.type_name(t)),
            "unary_expression" => n.child_by_field_name("operand").and_then(|o| self.expr_type(o)),
            "call_expression" => {
                let f = n.child_by_field_name("function")?;
                matches!(f.kind(), "identifier" | "selector_expression").then(|| format!("(){}", self.text(f)))
            }
            _ => None,
        }
    }

    fn assigned_to(&self, n: Node) -> Option<String> {
        let list = n.parent()?;
        if list.kind() != "expression_list" {
            return None;
        }
        let stmt = list.parent()?;
        if !matches!(stmt.kind(), "short_var_declaration" | "assignment_statement" | "var_spec") {
            return None;
        }
        let left = stmt.child_by_field_name("left").or_else(|| stmt.child_by_field_name("name"))?;
        if left.kind() == "expression_list" {
            nth_named(left, 0).map(|x| self.text(x).to_string())
        } else {
            Some(self.text(left).to_string())
        }
    }

    fn call(&self, n: Node) -> GoCall {
        let func = n.child_by_field_name("function");
        let (receiver, method) = match func {
            Some(f) if f.kind() == "selector_expression" => {
                let operand = f.child_by_field_name("operand");
                let method = f.child_by_field_name("field").map(|x| self.text(x).to_string()).unwrap_or_default();
                let recv = match operand.map(|o| o.kind()) {
                    Some("identifier") | Some("selector_expression") => {
                        let t = self.text(operand.unwrap());
                        if t.chars().all(|c| c.is_alphanumeric() || c == '_' || c == '.') { t.to_string() } else { CHAIN.to_string() }
                    }
                    _ => CHAIN.to_string(),
                };
                (Some(recv), method)
            }
            Some(f) if f.kind() == "identifier" => (None, self.text(f).to_string()),
            Some(f) => (Some(CHAIN.to_string()), self.text(f).chars().take(40).collect()),
            None => (None, String::new()),
        };
        let mut string_args = Vec::new();
        let mut ident_args = Vec::new();
        if let Some(args) = n.child_by_field_name("arguments") {
            let mut c = args.walk();
            for a in args.named_children(&mut c) {
                string_args.push(matches!(a.kind(), "interpreted_string_literal" | "raw_string_literal").then(|| self.string(a)));
                ident_args.push(matches!(a.kind(), "identifier" | "selector_expression").then(|| self.text(a).to_string()));
            }
        }
        GoCall { receiver, method, string_args, ident_args, assigned_to: self.assigned_to(n), composite: None, line: line(n) }
    }
}

fn nth_named(n: Node, i: usize) -> Option<Node> {
    let mut c = n.walk();
    n.named_children(&mut c).nth(i)
}
